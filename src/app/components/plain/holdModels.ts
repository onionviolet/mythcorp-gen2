export type HoldModelFrame = {
  scale: number;
  xOffset?: number;
  yOffset?: number;
  floatIntensity: number;
  rotationIntensity: number;
  floatSpeed: number;
  orbit: boolean;
  zoom: boolean;
  autoRotate: boolean;
  autoRotateSpeed: number;
  environmentIntensity: number;
};

export type HoldModelSource = {
  source: string;
  license: string;
  credit: string;
};

export type HoldModel = HoldModelSource & {
  id: string;
  label: string;
  src: `/${string}.glb`;
  frame: HoldModelFrame;
};

