export const DEFAULT_HOLD_MODEL_ID = 'spectre' satisfies HoldModelId;
export const DEFAULT_HOLD_MODEL = HOLD_MODELS[DEFAULT_HOLD_MODEL_ID];

export function resolveHoldModel(modelId?: string | null): HoldModel {
  if (modelId && Object.hasOwn(HOLD_MODELS, modelId)) {
    return HOLD_MODELS[modelId as HoldModelId];
  }

  return DEFAULT_HOLD_MODEL;
}
